"""IMG_3292 --montage: проверка сборки montage.py и «Чертежа» (19.10.2026) на настоящем дубле. Не выпуск: v3 собран page.py.

Обязательное (склейка, смена плана, вспышка после хука, тихие звуки, музыка) ставит сборка. «Чертёж» — по словам ролика:
1–5 на груди под счёт пальцев; сплит «IX век → книга» на Аль-Хорезми; маршрут Индия → Багдад → Европа за спиной на
«книгу перевели на латынь… Европа узнала»; X V I I I во весь кадр; клипы Flow (Индия, Хорезм) в рамке листа.
Факты: восточные «арабские» цифры ١٢٣ арабы зовут индийскими; кириллическая запись чисел — буквы под титлом (А=1, В=2, Г=3); аль-Хорезми, IX век, Багдад; Хорезм — низовья Амударьи; индийская десятичная запись — к V–VI вв.; трактат об индийском счёте; латинский перевод XII века; XVIII = 18.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import blueprint as bp  # noqa: E402
from montage import Montage  # noqa: E402

m = Montage("IMG_3292", "montage")
t = m.t
RED = "#F0352C"

# хук: «цифры на самом деле УЗБЕКСКИЕ» за головой
m.behind(f'        <div id="h-uz" class="g big" style="top: 262px; font-size: 150px; color: {RED};">узбекские</div>')
m.js(f'      slam("#h-uz", {t(1.94):.2f}, {{ fromScale: 1.5 }});\n'
     f'      leave("#h-uz", {t(2.70):.2f}, {{ y: -60, dur: 0.2 }});')
m.fg(t(0.95), t(2.95))
m.hide(t(0.95), t(2.75))
m.sound("uz1", "impact-bass-1", t(1.94), 0.9)
m.punch(t(1.94), t(2.70))

# 1 2 3 4 5 — на груди под счёт пальцев; субтитры этих слов прячутся (текст повторяет речь)
m.blueprint(bp.write("bp-15", "1 2 3 4 5", t(4.70), t(7.25), layout="chest", sub="«арабские»", dur=0.9))
m.hide(t(4.62), t(7.2))

# Индия — клип Flow в рамке листа
m.footage("ft-india", "a_india", t(11.0), round(t(13.62) - 0.25 - t(11.0), 2), label="Индия, V век")

# Аль-Хорезми: сплит, ось «IX век → книга»
m.blueprint(bp.timeline("bp-ix", [("IX век", "Багдад"), ("книга", "около 825 года")],
                        [t(13.62), t(16.46)], t(18.05), layout="split"))

# книгу перевели на латынь — маршрут цифр над головой: с востока (справа) на запад, дуги провисают за волосы
m.blueprint(bp.route("bp-way", [("Индия", 0.9, 0.2), ("Багдад", 0.5, 0.18), ("Европа", 0.1, 0.2)],
                     [t(20.04), t(20.76), t(21.62)], t(23.4), layout="behind", bend=-0.22))

# «сами арабы называют их индийскими» — на груди то, как пишут цифры сами арабы (перекличка с «1 2 3 4 5» в начале);
# дыра 23,4–38,3 с без вставок (19.10.2026, Валера на v2: «нет никаких вставок… динамика очень теряется»)
m.blueprint(bp.write("bp-ar", "١ ٢ ٣ ٤ ٥", t(26.08), t(29.1), layout="chest", sub="так пишут в Египте", dur=0.9))

# «на Руси до Петра писали числа буквами… с чёрточкой сверху» — сплит: «А В Г» пишутся, на «чёрточкой» над ними титла
m.blueprint(bp.write("bp-slav", "А В Г", t(63.2), t(67.45), layout="split", sub="= 1 2 3", dur=1.8,
                     over=t(66.5), titlo=True))

# гениально — штамп на груди
m.front('        <div id="st-gen" class="g stamp" data-safe="на груди ниже подбородка" '
        'style="left: 330px; top: 1250px; font-size: 72px; transform: rotate(-5deg);">гениально</div>')
m.js(f'      slam("#st-gen", {t(68.66):.2f}, {{ fromScale: 2.0, blur: 10, rot: -5 }});\n'
     f'      leave("#st-gen", {t(69.9):.2f}, {{ rot: -5 }});')
m.hide(t(68.6), t(69.32))

# X V I I I = 18 — лист во весь кадр
m.blueprint(bp.write("bp-xviii", "XVIII", t(71.78), t(74.0), layout="full", sub="= 18", dur=1.5))
# диктовка по буквам «икс, вэ, и, и, и» — субтитры «x v i i i» двоили бы число на листе (п.16)
m.hide(t(71.75), t(73.85))

# Хорезм — клип Flow в рамке листа
m.footage("ft-khor", "b_khorezm", t(78.27), round(t(80.77) - t(78.27), 2), label="низовья Амударьи")

# субтитры — правки распознавания из v3 (тот же дубль, те же номера слов)
v3 = json.loads((ROOT / "work/IMG_3292/director.json").read_text(encoding="utf-8"))
m.build("IMG_3292 — проверка montage.py и «Чертежа»", cta_at=t(85.72), cta_small="ЕГЭ на 80+ — переходи ко мне",
        text_fixes=v3["text_fixes"], keep_case=v3["keep_case"],
        # ключевые слова — одно на 5–8 с речи, красным и крупнее (caption_accent_scale): «субтитры одинаково скучно идут»
        accent_words=v3["accent_words"] + ["обоснованно", "вебинары", "латынь", "Пётр", "буквами", "главное", "математики"])
